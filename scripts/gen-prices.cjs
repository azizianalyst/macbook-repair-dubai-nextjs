// Generates src/content/prices.generated.ts from the admin price store (data/seo.json → .prices,
// or $SEO_DB). The /pricing visible tables AND the /pricing JSON-LD Offers both render from this,
// so a price edited once in the admin can never drift across surfaces. Runs in predev/prebuild
// (see package.json), like gen-routes / gen-screen-prices.
//
// SAFETY: if the store has no prices (e.g. a build without the data file), it leaves the existing
// committed src/content/prices.generated.ts untouched rather than wiping the site's prices.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "prices.generated.ts");
const GROUPS = ["macbook", "imac", "mac-desktop", "iphone", "ipad"];

function loadPrices() {
  try {
    const d = JSON.parse(fs.readFileSync(STORE, "utf8"));
    return Array.isArray(d.prices) ? d.prices : [];
  } catch {
    return [];
  }
}

const prices = loadPrices().slice().sort((a, b) => a.id - b.id);
if (!prices.length) {
  console.warn(`[gen-prices] no prices in store (${STORE}); keeping existing ${path.relative(ROOT, OUT)}`);
  process.exit(0);
}

const byGroup = Object.fromEntries(GROUPS.map((g) => [g, []]));
for (const p of prices) {
  (byGroup[p.group] || (byGroup[p.group] = [])).push({
    service: p.service, price: p.price, timeline: p.timeline, warranty: p.warranty,
  });
}

// JSON-LD service Offers: only rows that carry a schema_name. warranty is ISO-8601.
const services = prices
  .filter((p) => p.schema_name)
  .map((p) => {
    const o = { name: p.schema_name, price: p.price, timeline: p.timeline, warranty: p.warranty_iso || "P3M" };
    if (p.url) o.url = p.url;
    return o;
  });

const byKey = {};
for (const p of prices) if (p.key) byKey[p.key] = p.price;

const j = (x) => JSON.stringify(x, null, 2);
const out = `// AUTO-GENERATED by scripts/gen-prices.cjs from the admin price store — do not edit by hand.
// Single source of truth for the structured service prices: the /pricing tables (PRICE_ROWS_BY_GROUP)
// and the /pricing JSON-LD Offers (PRICING_SERVICES) both render from this, so prices can't drift.
// Edit prices in /admin/prices, then rebuild (prebuild runs gen-prices) to apply.
export type PriceRow = { service: string; price: number; timeline: string; warranty: string };
export type PricingService = { name: string; price: number; timeline: string; warranty: string; url?: string };

export const PRICE_ROWS_BY_GROUP: Record<string, PriceRow[]> = ${j(byGroup)};

export const PRICING_SERVICES: PricingService[] = ${j(services)};

const PRICE_BY_KEY: Record<string, number> = ${j(byKey)};
export const priceFor = (key: string): number | undefined => PRICE_BY_KEY[key];
`;

fs.writeFileSync(OUT, out);
console.log(`[gen-prices] wrote ${path.relative(ROOT, OUT)} (${prices.length} prices, ${services.length} JSON-LD offers)`);
