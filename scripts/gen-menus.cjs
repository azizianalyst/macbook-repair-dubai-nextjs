// Generates src/content/mega-menu.generated.ts from the admin Menus store (data/seo.json → .menus).
// Consumed by mega-menu.ts (re-exports MEGA_MENU) + Footer.tsx (FOOTER_COLUMNS). Runs in
// predev/prebuild after gen-routes. SAFETY: NEVER-WIPE — a blank menu must not break navigation.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "mega-menu.generated.ts");

let menus = null;
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); if (d.menus && typeof d.menus === "object") menus = d.menus; } catch {}

if (!menus || !Array.isArray(menus.header) || !Array.isArray(menus.footer)) {
  if (fs.existsSync(OUT)) { console.warn(`[gen-menus] no menus in store; keeping existing ${path.relative(ROOT, OUT)}`); process.exit(0); }
  console.error("[gen-menus] no menus in store AND no existing file — run `node scripts/seed-menus.cjs` first."); process.exit(1);
}

const out = `// AUTO-GENERATED by scripts/gen-menus.cjs from the admin Menus store — do not edit by hand.
// Edit the header + footer navigation in /admin/menus, then rebuild to apply.
import type { MegaPanel, FooterColumn } from "./mega-menu";

export const MEGA_MENU: MegaPanel[] = ${JSON.stringify(menus.header, null, 2)};

export const FOOTER_COLUMNS: FooterColumn[] = ${JSON.stringify(menus.footer, null, 2)};
`;
fs.writeFileSync(OUT, out);
console.log(`[gen-menus] wrote ${path.relative(ROOT, OUT)} (${menus.header.length} header panels, ${menus.footer.length} footer columns)`);
