// Generates src/content/redirects.generated.ts from the admin store — per-post (Blog Advanced tab)
// AND per-page (Page SEO Advanced tab) redirects. Consumed by src/proxy.ts. Runs in predev/prebuild
// after gen-blog + gen-pagemeta. Always written (empty => no redirects).
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "redirects.generated.ts");

let posts = [], pageMeta = [];
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); posts = Array.isArray(d.posts) ? d.posts : []; pageMeta = Array.isArray(d.pageMeta) ? d.pageMeta : []; } catch {}

const map = {};
// Published blog posts with a redirect set.
for (const p of posts) {
  if (p && p.status === "published" && p.slug && p.redirect && p.redirect.trim()) {
    map["/blog/" + p.slug] = { to: p.redirect.trim(), type: p.redirectType === "302" ? 302 : 301 };
  }
}
// Pages with a redirect set (path stored without trailing slash).
for (const m of pageMeta) {
  if (m && m.path && m.redirect && m.redirect.trim()) {
    map[m.path.replace(/\/+$/, "") || "/"] = { to: m.redirect.trim(), type: m.redirectType === "302" ? 302 : 301 };
  }
}

const out = `// AUTO-GENERATED by scripts/gen-redirects.cjs — per-post + per-page 301/302 redirects from the
// admin (Advanced tab). Consumed by src/proxy.ts. Keys are exact paths (no trailing slash).
export const REDIRECTS: Record<string, { to: string; type: 301 | 302 }> = ${JSON.stringify(map, null, 2)};
`;
fs.writeFileSync(OUT, out);
console.log(`[gen-redirects] wrote ${path.relative(ROOT, OUT)} (${Object.keys(map).length} redirects)`);
