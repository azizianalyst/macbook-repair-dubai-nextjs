// Generates src/content/business.generated.ts from the admin business store (data/seo.json → .business,
// or $SEO_DB). site.ts re-exports NAP / REVIEW_COUNT / REVIEW_AVERAGE / CONTENT_REVIEWED / HOURS from
// it, so editing the admin Business tab + rebuilding updates the whole site (footer, contact, schema).
// Runs in predev/prebuild. SAFETY: if the store has no business object, it keeps the existing file.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "business.generated.ts");

function loadBusiness() {
  try {
    const d = JSON.parse(fs.readFileSync(STORE, "utf8"));
    return d && typeof d.business === "object" ? d.business : null;
  } catch {
    return null;
  }
}

const b = loadBusiness();
if (!b) {
  console.warn(`[gen-business] no business in store (${STORE}); keeping existing ${path.relative(ROOT, OUT)}`);
  process.exit(0);
}

const waDigits = String(b.phoneE164 || "").replace(/[^0-9]/g, "");
const nap = {
  name: b.name, street: b.street, area: b.area, city: b.city, country: b.country,
  phoneDisplay: b.phoneDisplay, phoneE164: b.phoneE164,
  whatsappUrl: `https://wa.me/${waDigits}`,
  email: b.email || "",
  facebook: b.facebook || "", instagram: b.instagram || "", youtube: b.youtube || "",
  founded: b.founded || "", yearsInBusiness: b.yearsInBusiness ?? 0,
};
const hours = Array.isArray(b.hours) ? b.hours : [];

const j = (x) => JSON.stringify(x, null, 2);
const out = `// AUTO-GENERATED by scripts/gen-business.cjs from the admin business store — do not edit by hand.
// Edit in /admin/business, then rebuild (prebuild runs gen-business) to apply across the site.
export const NAP = ${j(nap)} as const;

export const REVIEW_COUNT = ${Number(b.reviewCount) || 0};
export const REVIEW_AVERAGE = ${Number(b.reviewAverage) || 0};
export const CONTENT_REVIEWED = ${JSON.stringify(b.contentReviewed || "")};

export const HOURS = ${j(hours)} as const;
`;

fs.writeFileSync(OUT, out);
console.log(`[gen-business] wrote ${path.relative(ROOT, OUT)} (${nap.name}, ${b.reviewCount} reviews)`);
