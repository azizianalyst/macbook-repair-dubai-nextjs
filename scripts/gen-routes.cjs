// Enumerate all app/ routes -> src/lib/routes.generated.ts (used by sitemap.ts).
const fs = require("fs"), path = require("path");
const APP = path.join(__dirname, "..", "src", "app");
function routes(dir, base = "") {
  let r = [];
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) r = r.concat(routes(path.join(dir, e.name), base + "/" + e.name));
    else if (e.name === "page.tsx") r.push(base || "/");
  }
  return r;
}
const list = [...new Set(routes(APP))].filter((p) => !p.includes("[")).sort();
fs.writeFileSync(
  path.join(__dirname, "..", "src", "lib", "routes.generated.ts"),
  "// AUTO-GENERATED by scripts/gen-routes.cjs — all static routes for the sitemap.\n" +
  "export const ROUTES: string[] = " + JSON.stringify(list, null, 2) + ";\n"
);
console.log("wrote " + list.length + " routes to routes.generated.ts");
