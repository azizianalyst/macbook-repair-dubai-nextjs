// Build-time helper: map each route path -> its real {title, description} by reading
// the view component (seoTitle/seoDescription props, const TITLE/DESC, or useSeo literals).
// Paths not extracted fall back to deriveMeta at runtime (page-meta.ts).
const fs = require("fs");
const path = require("path");

const APP = path.join(__dirname, "..", "src", "app");
const VIEWS = path.join(__dirname, "..", "src", "views");
const OUT = path.join(__dirname, "..", "src", "lib", "route-meta.generated.ts");

// Walk src/app for page.tsx files; route = dir path, view = its "@/views/X" import.
const routes = [];
(function walk(dir, base) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    if (e.isDirectory()) walk(path.join(dir, e.name), base + "/" + e.name);
    else if (e.name === "page.tsx") {
      const pathName = base || "/";
      if (pathName.includes("[")) continue; // dynamic routes get meta from dynamic-meta.ts
      const src = fs.readFileSync(path.join(dir, e.name), "utf8");
      const m = src.match(/(?:import\s+\w+|export\s*\{\s*default\s*\})\s+from\s+"@\/views\/([^"]+)"/);
      if (m) routes.push({ pathName, mod: m[1] });
    }
  }
})(APP, "");

// A quoted string literal with proper escape handling, for ", ' or `.
const STR = '("(?:\\\\.|[^"\\\\])*"|\'(?:\\\\.|[^\'\\\\])*\'|`(?:\\\\.|[^`\\\\])*`)';
const unquote = (raw) => {
  const body = raw.slice(1, -1);
  if (body.includes("${")) return null; // interpolated template -> not a static literal
  return body.replace(/\\(["'`\\])/g, "$1").replace(/\\n/g, " ").trim();
};
function grab(src, keyPattern) {
  const m = src.match(new RegExp(keyPattern + "\\s*[:=]\\s*" + STR));
  return m ? unquote(m[1]) : null;
}

const map = {};
let extracted = 0, fallback = 0;
for (const r of routes) {
  if (r.pathName === "/") continue;
  const file = path.join(VIEWS, r.mod + ".tsx");
  if (!fs.existsSync(file)) { fallback++; continue; }
  const src = fs.readFileSync(file, "utf8");
  const title =
    grab(src, "seoTitle") || grab(src, "\\bconst TITLE") ||
    grab(src, "useSeo\\([\\s\\S]*?title") || null;
  const desc =
    grab(src, "seoDescription") || grab(src, "\\bconst DESC") ||
    grab(src, "useSeo\\([\\s\\S]*?description") || null;
  if (title) {
    map[r.pathName] = { title, ...(desc ? { description: desc } : {}) };
    extracted++;
  } else {
    fallback++;
  }
}

const header = "// AUTO-GENERATED by scripts/extract-meta.cjs — do not edit by hand.\n" +
  "export const ROUTE_META: Record<string, { title: string; description?: string }> = ";
fs.writeFileSync(OUT, header + JSON.stringify(map, null, 2) + ";\n");
console.log("routes:", routes.length, "| extracted titles:", extracted, "| fallback:", fallback);
