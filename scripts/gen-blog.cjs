// Generates src/content/posts.generated.ts from the admin Blog store (data/seo.json -> .posts, or
// $SEO_DB). PUBLISHED posts only. Markdown -> HTML happens here (build time) so the public pages ship
// pre-rendered HTML with no runtime markdown cost. Consumed by:
//   - src/content/blog-posts.ts  (prepends ADMIN_POSTS to the POSTS registry -> index, sitemap, RSS)
//   - src/app/blog/[slug]/page.tsx (renders ADMIN_POST_RENDER through BlogPostTemplate)
// Runs in predev/prebuild. Sparse + additive: empty store => empty exports (always written), which
// is correct (no admin posts). The 85 hand-built TSX posts are never touched.
const fs = require("fs");
const path = require("path");
const MarkdownIt = require("markdown-it");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "posts.generated.ts");

// KEEP IN SYNC with src/lib/markdown.ts (the admin live-preview renderer).
const md = new MarkdownIt({ html: false, linkify: true, typographer: true, breaks: false });
const demoteH1 = (html) => html.replace(/<h1(\s[^>]*)?>/gi, "<h2>").replace(/<\/h1>/gi, "</h2>");
const render = (src) => demoteH1(md.render(src || ""));

const MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"];
function monthYear(iso) { // "2026-06-20" -> "June 2026"
  const m = /^(\d{4})-(\d{2})-/.exec(iso || "");
  if (!m) return "June 2026";
  return `${MONTHS[Number(m[2]) - 1] || "June"} ${m[1]}`;
}
function readingMinutes(markdown) {
  const words = (markdown || "").trim().split(/\s+/).filter(Boolean).length;
  return Math.max(1, Math.round(words / 200));
}

let posts = [];
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); posts = Array.isArray(d.posts) ? d.posts : []; } catch {}
// A scheduled post goes live once its scheduledFor date has arrived (checked at build time). Run a
// daily build/deploy to make scheduling effective. Published + due-scheduled posts, newest first.
const TODAY = new Date().toISOString().slice(0, 10);
const isLive = (p) => p && p.slug && (p.status === "published" || (p.status === "scheduled" && p.scheduledFor && p.scheduledFor <= TODAY));
const pub = posts.filter(isLive).sort((a, b) => (b.id || 0) - (a.id || 0));

const s = (x) => JSON.stringify(x ?? "");
const arr = (x) => JSON.stringify(x ?? []);

const listItems = pub.map((p) => {
  const date = monthYear(p.datePublished);
  const minutes = p.minutes || readingMinutes(p.body);
  return `  { slug: ${s("/blog/" + p.slug)}, title: ${s(p.title)}, excerpt: ${s(p.excerpt)}, category: ${s(p.category)}, author: ${s(p.author)}, date: ${s(date)}, minutes: ${minutes} },`;
}).join("\n");

const renderItems = pub.map((p) => {
  const path0 = "/blog/" + p.slug;
  const minutes = p.minutes || readingMinutes(p.body);
  const faqs = (Array.isArray(p.faqs) ? p.faqs : []).map((f) => ({ q: f.q, a: f.a }));
  const related = (Array.isArray(p.relatedLinks) ? p.relatedLinks : []).map((r) => ({ label: r.label, href: r.href, description: r.description || undefined }));
  // Social overrides (blank => derive at render from SEO title/description/hero).
  const og = { title: p.ogTitle || "", description: p.ogDescription || "", image: p.ogImage || "" };
  const twitter = { card: p.twitterCard || "", title: p.twitterTitle || "", description: p.twitterDescription || "", image: p.twitterImage || "" };
  const robots = { noindex: !!p.noindex, nofollow: !!p.nofollow, noarchive: !!p.noarchive, noimageindex: !!p.noimageindex, nosnippet: !!p.nosnippet };
  return `  ${s(p.slug)}: {
    path: ${s(path0)},
    seoTitle: ${s(p.seoTitle || p.title)},
    seoDescription: ${s(p.seoDescription || p.excerpt)},
    category: ${s(p.category)},
    h1: ${s(p.title)},
    hook: ${s(p.excerpt)},
    quickAnswer: ${s(p.quickAnswer || p.excerpt)},
    author: { name: ${s(p.author)}, role: ${s(p.authorRole || "Apple repair specialist")} },
    datePublished: ${s(p.datePublished)},
    dateModified: ${s(p.dateModified || p.datePublished)},
    readingMinutes: ${minutes},
    featuredImageAlt: ${s(p.heroAlt || p.title)},
    featuredImage: ${p.heroImage ? s(p.heroImage) : "undefined"},
    html: ${s(render(p.body))},
    faqs: ${arr(faqs)},
    relatedLinks: ${arr(related)},
    schemaType: ${s(p.schemaType || "Article")},
    breadcrumbTitle: ${s(p.breadcrumbTitle || "")},
    canonical: ${s(p.canonical || "")},
    og: ${JSON.stringify(og)},
    twitter: ${JSON.stringify(twitter)},
    robots: ${JSON.stringify(robots)},
  },`;
}).join("\n");
// (Per-post redirects are emitted by scripts/gen-redirects.cjs, which reads posts + pages together.)

const out = `// AUTO-GENERATED by scripts/gen-blog.cjs from the admin Blog store — do not edit by hand.
// Write/edit posts in /admin/blog (markdown), then rebuild (prebuild runs gen-blog) to publish.
// PUBLISHED posts only. The 85 hand-built TSX posts live in their own folders and are unaffected.
import type { Post } from "./blog-posts";

export type AdminFaq = { q: string; a: string };
export type AdminRelated = { label: string; href: string; description?: string };
export type AdminPostRender = {
  path: string;
  seoTitle: string;
  seoDescription: string;
  category: string;
  h1: string;
  hook: string;
  quickAnswer: string;
  author: { name: string; role: string };
  datePublished: string;
  dateModified: string;
  readingMinutes: number;
  featuredImageAlt: string;
  featuredImage?: string;
  html: string;            // pre-rendered markdown
  faqs: AdminFaq[];
  relatedLinks: AdminRelated[];
  schemaType: "Article" | "BlogPosting" | "NewsArticle" | "None";
  breadcrumbTitle: string;
  canonical: string;
  og: { title: string; description: string; image: string };
  twitter: { card: string; title: string; description: string; image: string };
  robots: { noindex: boolean; nofollow: boolean; noarchive: boolean; noimageindex: boolean; nosnippet: boolean };
};

// Listing metadata — prepended to POSTS so index + sitemap + RSS include admin posts (newest first).
export const ADMIN_POSTS: Post[] = [
${listItems}
];

// Full render payload, keyed by bare slug (no /blog/ prefix). Served by /blog/[slug].
export const ADMIN_POST_RENDER: Record<string, AdminPostRender> = {
${renderItems}
};

// Slugs for generateStaticParams on the /blog/[slug] route.
export const ADMIN_POST_SLUGS: string[] = ${JSON.stringify(pub.map((p) => p.slug))};
`;

fs.writeFileSync(OUT, out);
console.log(`[gen-blog] wrote ${path.relative(ROOT, OUT)} (${pub.length} published admin post${pub.length === 1 ? "" : "s"})`);
