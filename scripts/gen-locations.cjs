// Generates src/content/areas-overrides.generated.ts + cities-overrides.generated.ts from the admin
// store (.areaOverrides / .cityOverrides). SPARSE OVERRIDE maps (slug → editable prose/FAQs) that
// areas.ts/cities.ts merge over their base configs. Runs in predev/prebuild. Always written (empty =
// {} = no overrides, which is correct).
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");

let areaOverrides = [], cityOverrides = [];
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); areaOverrides = Array.isArray(d.areaOverrides) ? d.areaOverrides : []; cityOverrides = Array.isArray(d.cityOverrides) ? d.cityOverrides : []; } catch {}

function toMap(list) {
  const map = {};
  for (const o of list) {
    if (!o || !o.slug) continue;
    const e = {};
    for (const [k, v] of Object.entries(o)) {
      if (k === "slug") continue;
      if (Array.isArray(v)) { if (v.length) e[k] = v; }
      else if (typeof v === "string") { if (v.trim()) e[k] = v; }
      else if (v != null) e[k] = v;
    }
    if (Object.keys(e).length) map[o.slug] = e;
  }
  return map;
}

function write(file, exportName, map) {
  const out = `// AUTO-GENERATED by scripts/gen-locations.cjs from the admin store — do not edit by hand.
// Sparse per-slug overrides (prose + FAQs) merged over the base configs. Edit in /admin/locations.
export const ${exportName}: Record<string, Record<string, unknown>> = ${JSON.stringify(map, null, 2)};
`;
  fs.writeFileSync(path.join(ROOT, "src", "content", file), out);
}

const aMap = toMap(areaOverrides), cMap = toMap(cityOverrides);
write("areas-overrides.generated.ts", "AREA_OVERRIDES", aMap);
write("cities-overrides.generated.ts", "CITY_OVERRIDES", cMap);
console.log(`[gen-locations] wrote area+city overrides (${Object.keys(aMap).length} areas, ${Object.keys(cMap).length} cities)`);
