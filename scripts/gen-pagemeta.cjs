// Generates src/lib/page-meta-overrides.generated.ts from the admin Page SEO store
// (data/seo.json → .pageMeta, or $SEO_DB). dynamic-meta.ts adminMetaOverride() reads it and
// metaForPath applies it (title/description/robots/canonical/OG/Twitter — highest precedence, per
// field). Runs in predev/prebuild. Sparse + additive: empty store => empty map, so always write.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "lib", "page-meta-overrides.generated.ts");

let pageMeta = [];
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); pageMeta = Array.isArray(d.pageMeta) ? d.pageMeta : []; } catch {}

const str = (o, k, v) => { if (v && String(v).trim()) o[k] = String(v).trim(); };
const bool = (o, k, v) => { if (v === true) o[k] = true; };

const map = {};
for (const m of pageMeta) {
  if (!m || !m.path) continue;
  const o = {};
  str(o, "title", m.title);
  str(o, "description", m.description);
  str(o, "ogTitle", m.ogTitle);
  str(o, "ogDescription", m.ogDescription);
  str(o, "ogImage", m.ogImage);
  if (m.twitterCard) o.twitterCard = m.twitterCard;
  str(o, "twitterTitle", m.twitterTitle);
  str(o, "twitterDescription", m.twitterDescription);
  str(o, "twitterImage", m.twitterImage);
  str(o, "canonical", m.canonical);
  bool(o, "noindex", m.noindex);
  bool(o, "nofollow", m.nofollow);
  bool(o, "noarchive", m.noarchive);
  bool(o, "noimageindex", m.noimageindex);
  bool(o, "nosnippet", m.nosnippet);
  if (Object.keys(o).length) map[m.path] = o;
}

const out = `// AUTO-GENERATED by scripts/gen-pagemeta.cjs from the admin Page SEO store — do not edit by hand.
// Edit pages in /admin/pageseo, then rebuild to apply. Sparse: only customised paths.
export type PageMetaOverride = {
  title?: string; description?: string;
  ogTitle?: string; ogDescription?: string; ogImage?: string;
  twitterCard?: "summary_large_image" | "summary"; twitterTitle?: string; twitterDescription?: string; twitterImage?: string;
  canonical?: string;
  noindex?: boolean; nofollow?: boolean; noarchive?: boolean; noimageindex?: boolean; nosnippet?: boolean;
};
export const META_OVERRIDES: Record<string, PageMetaOverride> = ${JSON.stringify(map, null, 2)};
`;
fs.writeFileSync(OUT, out);
console.log(`[gen-pagemeta] wrote ${path.relative(ROOT, OUT)} (${Object.keys(map).length} page-SEO overrides)`);
