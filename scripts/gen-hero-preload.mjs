#!/usr/bin/env node
// Emits src/lib/hero-preload.generated.ts — the set of routes whose view actually
// renders the Hero image that <PageSchema> preloads.
//
// Why this exists: heroPreload() fired for every isServicePath(), on the assumption
// that "service path" meant "rendered by SubServicePageTemplate". It does not. Forty
// routes use bespoke views that render a DIFFERENT image (their topic infographic),
// so each of those pages issued a fetchPriority=high preload for a ~200KB AVIF it
// never displayed — wasted bandwidth competing with the real LCP candidate, and the
// "preloaded but not used" console warning visible on the live site. (audit 2026-09-23)
//
// Usage: node scripts/gen-hero-preload.mjs

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from "node:fs";
import path from "node:path";

const ROOT = process.cwd();
const APP = path.join(ROOT, "src/app");
const VIEWS = path.join(ROOT, "src/views");
const COMPONENTS = path.join(ROOT, "src/components");
const OUT = path.join(ROOT, "src/lib/hero-preload.generated.ts");

const MARKER = "SubServicePageTemplate";

// Resolve a module name to a file under src/views or src/components/blocks.
function resolve(name) {
  for (const base of [VIEWS, path.join(COMPONENTS, "blocks"), COMPONENTS]) {
    for (const ext of [".tsx", ".ts"]) {
      const p = path.join(base, name + ext);
      if (existsSync(p)) return p;
    }
  }
  return null;
}

// Does this module render SubServicePageTemplate, directly or through one hop?
const cache = new Map();
function usesTemplate(file, depth = 0) {
  if (!file || depth > 3) return false;
  if (cache.has(file)) return cache.get(file);
  cache.set(file, false); // cycle guard
  const s = readFileSync(file, "utf8");
  let hit = s.includes(MARKER);
  if (!hit) {
    for (const m of s.matchAll(/from "@\/(?:views|components(?:\/blocks)?)\/([A-Za-z0-9_]+)"/g)) {
      if (usesTemplate(resolve(m[1]), depth + 1)) { hit = true; break; }
    }
  }
  cache.set(file, hit);
  return hit;
}

const routes = [];
(function walk(dir) {
  for (const e of readdirSync(dir)) {
    const p = path.join(dir, e);
    if (statSync(p).isDirectory()) { walk(p); continue; }
    if (e !== "page.tsx") continue;
    let url = "/" + path.relative(APP, path.dirname(p)).split(path.sep).join("/");
    if (url === "/.") url = "/";
    if (url.startsWith("/admin") || url.includes("[")) continue;
    const src = readFileSync(p, "utf8");
    const view = src.match(/from "@\/views\/([A-Za-z0-9_]+)"/)?.[1];
    if (!view) continue;
    if (usesTemplate(resolve(view))) routes.push(url);
  }
})(APP);

routes.sort();
writeFileSync(OUT,
`// AUTO-GENERATED by scripts/gen-hero-preload.mjs - do not edit by hand.
// Routes whose view renders the Hero image that PageSchema preloads. Any route NOT in
// this set renders a different image, so preloading the Hero candidate there would be a
// high-priority fetch of a file the page never shows.
export const HERO_PRELOAD_ROUTES: ReadonlySet<string> = new Set([
${routes.map((r) => `  ${JSON.stringify(r)},`).join("\n")}
]);
`);
console.log(`wrote ${path.relative(ROOT, OUT)} (${routes.length} routes render the preloaded hero)`);
