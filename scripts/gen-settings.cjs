// Generates src/content/settings.generated.ts from the admin Site Settings store (data/seo.json →
// .settings, or $SEO_DB). Consumed by site.ts (SITEMAP_LAST_UPDATED), schema.ts (org slogan),
// page-meta.ts (noindex switches), robots.ts (site kill-switch). Runs in predev/prebuild.
// SAFETY: NEVER-WIPE — empty store keeps the existing file (a blank settings must not deindex/blank
// the live site). On the very first run with no store + no file, writes safe defaults.
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "settings.generated.ts");

const DEFAULTS = {
  tagline: "Independent Apple Repair Specialists",
  sitemapLastmod: "2026-06-18",
  timezone: "Asia/Dubai",
  siteNoindex: false,
  homepageNoindex: false,
};

let settings = null;
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); if (d.settings && typeof d.settings === "object") settings = d.settings; } catch {}

if (!settings) {
  if (fs.existsSync(OUT)) {
    console.warn(`[gen-settings] no settings in store (${STORE}); keeping existing ${path.relative(ROOT, OUT)}`);
    process.exit(0);
  }
  settings = DEFAULTS; // first run, no store + no file → safe defaults
}

const s = { ...DEFAULTS, ...settings };
const out = `// AUTO-GENERATED by scripts/gen-settings.cjs from the admin Site Settings store — do not edit by hand.
// Edit in /admin/settings, then rebuild to apply.
export const SITE_SETTINGS = {
  tagline: ${JSON.stringify(s.tagline || DEFAULTS.tagline)},
  sitemapLastmod: ${JSON.stringify(s.sitemapLastmod || DEFAULTS.sitemapLastmod)},
  timezone: ${JSON.stringify(s.timezone || DEFAULTS.timezone)},
  siteNoindex: ${s.siteNoindex === true},
  homepageNoindex: ${s.homepageNoindex === true},
} as const;
`;
fs.writeFileSync(OUT, out);
console.log(`[gen-settings] wrote ${path.relative(ROOT, OUT)} (noindex=${s.siteNoindex === true}, lastmod=${s.sitemapLastmod})`);
