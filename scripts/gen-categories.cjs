// Generates src/content/blog-taxonomy.generated.ts (CATEGORIES + TAGS) from the admin store
// (.taxonomy). Consumed by blog-posts.ts (re-exports). Runs in predev/prebuild after gen-routes.
// SAFETY: NEVER-WIPE + HUB-ROUTE GUARD — the category/tag slugs are hardcoded route folders
// (src/app/blog/<slug>, src/app/blog/tag/<slug>); if the store is missing a required slug (a bad edit
// somehow bypassed the API), refuse and keep the existing file so no hub route renders empty.
const fs = require("fs");
const path = require("path");
const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "blog-taxonomy.generated.ts");

const REQUIRED_HUBS = ["repair-costs", "fixes", "buying-guides", "sell-trade-in", "care-maintenance", "apple-news", "why-us"];
const REQUIRED_TAGS = ["macbook", "iphone", "ipad", "imac", "mac"];

let tax = null;
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); if (d.taxonomy && typeof d.taxonomy === "object") tax = d.taxonomy; } catch {}

function keep(reason) {
  if (fs.existsSync(OUT)) { console.warn(`[gen-categories] ${reason}; keeping existing ${path.relative(ROOT, OUT)}`); process.exit(0); }
  console.error(`[gen-categories] ${reason} AND no existing file — run \`node scripts/seed-categories.cjs\` first.`); process.exit(1);
}

if (!tax || !Array.isArray(tax.categories) || !Array.isArray(tax.tags)) keep("no taxonomy in store");
const catSlugs = new Set(tax.categories.map((c) => c.slug));
const tagSlugs = new Set(tax.tags.map((t) => t.slug));
const missingHub = REQUIRED_HUBS.find((s) => !catSlugs.has(s));
const missingTag = REQUIRED_TAGS.find((s) => !tagSlugs.has(s));
if (missingHub) keep(`GUARD: required category hub "${missingHub}" missing from store (would break /blog/${missingHub})`);
if (missingTag) keep(`GUARD: required tag "${missingTag}" missing from store (would break /blog/tag/${missingTag})`);

const out = `// AUTO-GENERATED by scripts/gen-categories.cjs from the admin taxonomy store — do not edit by hand.
// Edit blog category copy/mapping + tag names in /admin/categories, then rebuild to apply.
// Slugs are LOCKED to the hub route folders (the admin API + this generator's guard enforce it).
import type { BlogCategory } from "./blog-posts";

export const CATEGORIES: BlogCategory[] = ${JSON.stringify(tax.categories, null, 2)};

export const TAGS: { slug: string; name: string }[] = ${JSON.stringify(tax.tags, null, 2)};
`;
fs.writeFileSync(OUT, out);
console.log(`[gen-categories] wrote ${path.relative(ROOT, OUT)} (${tax.categories.length} categories, ${tax.tags.length} tags)`);
