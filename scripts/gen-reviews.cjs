// Generates src/content/reviews.ts from the admin Reviews store (data/seo.json → .reviews, or
// $SEO_DB). Consumed by find-reviews.ts + page-schema.ts. Edit in /admin/reviews, rebuild to apply.
// Runs in predev/prebuild. SAFETY: empty store -> keep existing reviews.ts (never wipe).
const fs = require("fs");
const path = require("path");

const ROOT = path.join(__dirname, "..");
const STORE = process.env.SEO_DB || path.join(ROOT, "data", "seo.json");
const OUT = path.join(ROOT, "src", "content", "reviews.ts");

let reviews = [];
try { const d = JSON.parse(fs.readFileSync(STORE, "utf8")); reviews = Array.isArray(d.reviews) ? d.reviews : []; } catch {}
if (!reviews.length) {
  console.warn(`[gen-reviews] no reviews in store (${STORE}); keeping existing ${path.relative(ROOT, OUT)}`);
  process.exit(0);
}

const s = (x) => JSON.stringify(x);
// The store keeps Google's date verbatim. Relative ones ("2 weeks ago") were copied on an
// unrecorded day and froze in the static HTML, so they go false a week later (t34). The
// capture date is unknown, so no real date can be derived: publish absolute dates only
// and leave relative ones blank (every render site shows a date only when there is one).
const siteDate = (d) => (typeof d === "string" && !/\bago\b/i.test(d) ? d.trim() : "");
const items = reviews
  .map((r) => `  { name: ${s(r.name)}, date: ${s(siteDate(r.date))}, rating: ${Number(r.rating) || 5}, text: ${s(r.text)}, language: ${s(r.language)}, services: ${s(r.services || [])} },`)
  .join("\n");

const out = `// AUTO-GENERATED by scripts/gen-reviews.cjs from the admin Reviews store — do not edit by hand.
// Edit reviews in /admin/reviews, then rebuild (prebuild runs gen-reviews) to apply.
import type { Review } from "@/components/blocks/ReviewCard";

export type ReviewLanguage = "English" | "Russian" | "German" | "French" | "Turkish" | "Arabic";
export type ReviewService  = "MacBook" | "iMac" | "iPhone" | "iPad" | "Water Damage" | "Battery" | "Screen" | "Keyboard";

export type TaggedReview = Review & {
  language: ReviewLanguage;
  services: ReviewService[];
};

export const REVIEWS: TaggedReview[] = [
${items}
];

// Free pickup and delivery ended 2026-10-15: skip reviews that praise it when showcasing
// (they stay verbatim on /reviews). Each index walks forward to the next usable review.
const ENDED_SERVICE_RE = /\\b(free )?(pick-?up|collection|delivery|courier|door[- ]to[- ]door|collected)\\b/i;
export function pickReviews(indices: number[]): Review[] {
  const used = new Set<number>();
  return indices.map((i) => {
    for (let k = 0; k < REVIEWS.length; k++) {
      const j = (i + k) % REVIEWS.length;
      if (!used.has(j) && !ENDED_SERVICE_RE.test(REVIEWS[j].text ?? "")) { used.add(j); return REVIEWS[j]; }
    }
    return REVIEWS[i % REVIEWS.length];
  });
}
`;

fs.writeFileSync(OUT, out);
console.log(`[gen-reviews] wrote ${path.relative(ROOT, OUT)} (${reviews.length} reviews)`);
